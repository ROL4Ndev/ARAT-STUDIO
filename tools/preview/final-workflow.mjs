const open = async (target, path, status = 200) => assert.equal((await target.goto(base + path, { waitUntil: 'networkidle' })).status(), status, path);
const submit = async (target, label) => {
    await target.getByRole('button', { name: label, exact: true }).click();
    await target.waitForLoadState('networkidle');
};
const shot = async (target, name) => {
    await target.evaluate(async () => {
        scrollTo({ top: 0, behavior: 'instant' });
        await document.fonts.ready;
    });
    assert.equal(await target.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, name);
    await target.screenshot({ path: `${output}/${name}.png`, fullPage: true });
};
